// Generates android/kotlin/themechanics/compose/TmColors.kt from
// src/the-mechanics/themes.css, so the Jetpack Compose colors can never drift
// from the CSS themes. The output is committed (Android apps consume the
// repository directly); rerun after any change to themes.css:
//   corepack pnpm build:compose
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const css = readFileSync(join(root, "src/the-mechanics/themes.css"), "utf8");
const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const out = join(root, "android/kotlin/themechanics/compose/TmColors.kt");

const themes = ["light", "dark", "coffee"];
const blocks = {};
for (const [, sel, body] of css.matchAll(/([^{}]*\[data-tm-theme="\w+"\][^{]*)\{([^}]*)\}/g)) {
  const name = sel.match(/\[data-tm-theme="(\w+)"\]\s*$/)?.[1];
  if (themes.includes(name)) blocks[name] = Object.fromEntries([...body.matchAll(/--tm-([\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
}
for (const t of themes) if (!blocks[t]) throw new Error(`theme block not found: ${t}`);

const h2 = (n) => Number(n).toString(16).padStart(2, "0").toUpperCase();
// #rrggbb or rgb(r g b / a), also the color inside a box-shadow value.
function color(value) {
  let m = value.match(/^#([0-9a-f]{6})$/i);
  if (m) return `Color(0xFF${m[1].toUpperCase()})`;
  m = value.match(/rgb\((\d+) (\d+) (\d+) \/ ([\d.]+)\)/);
  if (m) return `Color(0x${h2(Math.round(Number(m[4]) * 255))}${h2(m[1])}${h2(m[2])}${h2(m[3])})`;
  return null;
}
const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());

const keys = Object.keys(blocks.light);
for (const t of themes) {
  const a = keys.join(), b = Object.keys(blocks[t]).join();
  if (a !== b) throw new Error(`theme ${t} does not define the same tokens as light`);
}
const colorKeys = keys.filter((k) => color(blocks.light[k]));
const doc = (k) => blocks.light[k].startsWith("#") || blocks.light[k].startsWith("rgb") ? "" : `  // color of --tm-${k}`;

let kt = `// GENERATED by scripts/build-compose.mjs from src/the-mechanics/themes.css
// (The Mechanics ${version}). Do not edit; run \`corepack pnpm build:compose\`.
package themechanics.compose

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color

/** One theme's color roles; names follow the \`--tm-*\` CSS tokens. */
@Immutable
data class TmColors(
    val name: TmThemeName,
    val isDark: Boolean,
${colorKeys.map((k) => `    val ${camel(k)}: Color,${doc(k)}`).join("\n")}
    val chartFillOpacity: Float,
)

enum class TmThemeName { Light, Dark, Coffee }

`;
for (const t of themes) {
  const b = blocks[t];
  const Name = t[0].toUpperCase() + t.slice(1);
  kt += `val Tm${Name}Colors = TmColors(
    name = TmThemeName.${Name},
    isDark = ${t !== "light"},
${colorKeys.map((k) => `    ${camel(k)} = ${color(b[k])},`).join("\n")}
    chartFillOpacity = ${Number(b["chart-fill-opacity"])}f,
)

`;
}
writeFileSync(out, kt.trimEnd() + "\n");
console.log(`wrote ${out.slice(root.length + 1)} (${colorKeys.length} colors × ${themes.length} themes)`);

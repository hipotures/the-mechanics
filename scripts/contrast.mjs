// WCAG 2.x contrast check of essential token pairs in all three themes.
// Parses src/the-mechanics/themes.css (hex values only) and writes
// docs/verification/contrast.md. Exit code 1 if any required pair fails.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const css = readFileSync("src/the-mechanics/themes.css", "utf8");
const themes = {};
for (const [, sel, body] of css.matchAll(/((?:\[data-tm-theme="\w+"\]|:root)[^{]*)\{([^}]*)\}/g)) {
  const id = sel.match(/data-tm-theme="(\w+)"/)?.[1];
  if (!id) continue;
  themes[id] = Object.fromEntries([...body.matchAll(/--tm-([\w-]+):\s*(#[0-9a-f]{6})/gi)].map(([, k, v]) => [k, v]));
}

const lum = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};

// [foreground, background, minimum, purpose]
const T = 4.5, G = 3;
const pairs = [
  ["text", "surface", T, "body text on panel"],
  ["text", "canvas", T, "body text on canvas"],
  ["text", "chrome", T, "text in topbar/sidebar"],
  ["text-2", "chrome", T, "nav items"],
  ["text-3", "chrome", T, "sidebar meta text"],
  ["line-1", "chrome", G, "shell boundary"],
  ["text-2", "surface", T, "secondary text on panel"],
  ["text-2", "head-1", T, "region header labels"],
  ["text-3", "surface", T, "muted/meta text on panel"],
  ["text-3", "canvas", T, "muted text on canvas"],
  ["text-3", "sunken", T, "record label metadata"],
  ["text", "select-bg", T, "text in selected row"],
  ["text", "inset", T, "input value"],
  ["text-3", "inset", T, "input placeholder"],
  ["accent-text", "accent", T, "primary button label"],
  ["link", "surface", T, "link on panel"],
  ["text-inverse", "inverse", T, "count badge / tooltip"],
  ["success", "success-soft", T, "success badge text"],
  ["warning", "warning-soft", T, "warning badge text"],
  ["danger", "danger-soft", T, "danger badge text"],
  ["info", "info-soft", T, "info badge text"],
  ["pending", "pending-soft", T, "pending badge text"],
  ["offline", "offline-soft", T, "offline badge text"],
  ["danger", "surface", T, "error message / negative number"],
  ["success", "surface", T, "positive trend"],
  ["warning", "surface", T, "warning text on panel"],
  ["surface", "danger", T, "danger button label"],
  ["line-1", "surface", G, "Level 1 boundary"],
  ["line-1", "canvas", G, "Level 1 boundary vs canvas"],
  ["line-2", "surface", G, "Level 2 boundary (panel, card, table)"],
  ["line-2", "canvas", G, "Level 2 boundary vs canvas"],
  ["line-input", "inset", G, "form control boundary"],
  ["focus", "surface", G, "focus ring on panel"],
  ["focus", "canvas", G, "focus ring on canvas"],
  ["select-line", "select-bg", G, "selection marker"],
  ...[1, 2, 3, 4, 5, 6, 7, 8].map((i) => [`chart-${i}`, "surface", G, `chart series ${i}`]),
  ["chart-axis", "surface", G, "chart axis"],
  ["chart-threshold", "surface", G, "threshold line/label"],
];
// Informational (no WCAG minimum): hierarchy and disabled pairs.
const info = [
  ["line-3", "surface", "Level 3 hairline (decorative separator)"],
  ["surface", "canvas", "surface vs canvas separation"],
  ["head-1", "surface", "region head band vs body"],
  ["text-disabled", "surface", "disabled text (exempt per WCAG 1.4.3)"],
];

let failures = 0;
let md = `# Contrast verification\n\nGenerated by \`pnpm check:contrast\` from \`src/the-mechanics/themes.css\`. WCAG 2.x relative-luminance ratios. Required: 4.5:1 text, 3:1 graphics/control boundaries (1.4.11). Only solid token pairs are checked; translucent hover tints and color-mix() values are not.\n\n`;
for (const [id, t] of Object.entries(themes)) {
  md += `## ${id}\n\n| Foreground | Background | Ratio | Min | Result | Purpose |\n|---|---|---:|---:|---|---|\n`;
  for (const [f, b, min, why] of pairs) {
    const r = ratio(t[f], t[b]);
    const ok = r >= min;
    if (!ok) failures++;
    md += `| \`${f}\` ${t[f]} | \`${b}\` ${t[b]} | ${r.toFixed(2)} | ${min} | ${ok ? "pass" : "**FAIL**"} | ${why} |\n`;
  }
  md += `\nInformational:\n\n| Pair | Ratio | Note |\n|---|---:|---|\n`;
  for (const [f, b, why] of info) md += `| \`${f}\` / \`${b}\` | ${ratio(t[f], t[b]).toFixed(2)} | ${why} |\n`;
  md += "\n";
}
mkdirSync("docs/verification", { recursive: true });
writeFileSync("docs/verification/contrast.md", md);
console.log(`${Object.keys(themes).length} themes, ${pairs.length} pairs each, ${failures} failures → docs/verification/contrast.md`);
if (failures) {
  for (const [id, t] of Object.entries(themes))
    for (const [f, b, min] of pairs) if (ratio(t[f], t[b]) < min) console.log(` FAIL ${id}: ${f} on ${b} = ${ratio(t[f], t[b]).toFixed(2)} < ${min}`);
  process.exit(1);
}
